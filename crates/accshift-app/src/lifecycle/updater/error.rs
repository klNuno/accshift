//! `tauri-plugin-updater` 2.11.0 `src/error.rs`, the variants this port can
//! produce, with the same `Display` strings.
//!
//! The TS side never saw a variant: the plugin serialized the error through
//! `Display` and `useAppUpdater` sorted the string with regular expressions
//! ([`super::super::update_flow::classify_update_check_error`]). The strings
//! are therefore the contract. The plugin's `#[error(transparent)]` variants
//! keep the source's own message here; they hold it as text so this file
//! needs nothing but `std` (it is shared with the Linux and macOS installers).

use std::fmt;

#[derive(Debug)]
#[non_exhaustive]
pub enum UpdaterError {
    /// error.rs line 13.
    EmptyEndpoints,
    /// Transparent `std::io::Error`.
    Io(std::io::Error),
    /// Transparent `semver::Error`.
    Semver(String),
    /// Transparent `serde_json::Error`.
    Serialization(String),
    /// error.rs line 25.
    ReleaseNotFound,
    /// error.rs line 28.
    UnsupportedArch,
    /// error.rs line 31.
    UnsupportedOs,
    /// error.rs line 34.
    FailedToDetermineExtractPath,
    /// Transparent `url::ParseError`.
    UrlParse(String),
    /// Transparent `reqwest::Error`.
    Reqwest(String),
    /// error.rs line 43.
    TargetNotFound(String),
    /// error.rs lines 46-49.
    TargetsNotFound(Vec<String>),
    /// error.rs line 51, "`{0}`".
    Network(String),
    /// Transparent `minisign_verify::Error`.
    Minisign(String),
    /// Transparent `base64::DecodeError`.
    Base64(String),
    /// error.rs line 60.
    SignatureUtf8(String),
    /// error.rs line 67.
    TempDirNotOnSameMountPoint,
    /// error.rs line 69.
    BinaryNotFoundInArchive,
    /// error.rs line 71.
    TempDirNotFound,
    /// error.rs line 73.
    AuthenticationFailed,
    /// error.rs line 77.
    PackageInstallFailed,
    /// error.rs line 79.
    InvalidUpdaterFormat,
    /// error.rs line 90.
    InsecureTransportProtocol,
}

impl fmt::Display for UpdaterError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyEndpoints => f.write_str("Updater does not have any endpoints set."),
            Self::Io(error) => error.fmt(f),
            Self::Semver(text)
            | Self::Serialization(text)
            | Self::UrlParse(text)
            | Self::Reqwest(text)
            | Self::Minisign(text)
            | Self::Base64(text) => f.write_str(text),
            Self::ReleaseNotFound => {
                f.write_str("Could not fetch a valid release JSON from the remote")
            }
            Self::UnsupportedArch => f.write_str(
                "Unsupported application architecture, expected one of `x86`, `x86_64`, `arm` or `aarch64`.",
            ),
            Self::UnsupportedOs => {
                f.write_str("Unsupported OS, expected one of `linux`, `darwin` or `windows`.")
            }
            Self::FailedToDetermineExtractPath => {
                f.write_str("Failed to determine updater package extract path.")
            }
            Self::TargetNotFound(target) => write!(
                f,
                "the platform `{target}` was not found in the response `platforms` object"
            ),
            Self::TargetsNotFound(targets) => write!(
                f,
                "None of the fallback platforms `{targets:?}` were found in the response `platforms` object"
            ),
            Self::Network(text) => write!(f, "`{text}`"),
            Self::SignatureUtf8(signature) => write!(
                f,
                "The signature {signature} could not be decoded, please check if it is a valid base64 string. The signature must be the contents of the `.sig` file generated by the Tauri bundler, as a string."
            ),
            Self::TempDirNotOnSameMountPoint => {
                f.write_str("temp directory is not on the same mount point as the AppImage")
            }
            Self::BinaryNotFoundInArchive => {
                f.write_str("binary for the current target not found in the archive")
            }
            Self::TempDirNotFound => f.write_str("failed to create temporary directory"),
            Self::AuthenticationFailed => f.write_str("Authentication failed or was cancelled"),
            Self::PackageInstallFailed => f.write_str("Failed to install package"),
            Self::InvalidUpdaterFormat => f.write_str("invalid updater binary format"),
            Self::InsecureTransportProtocol => f.write_str(
                "The configured updater endpoint must use a secure protocol like `https`.",
            ),
        }
    }
}

impl std::error::Error for UpdaterError {}

impl From<std::io::Error> for UpdaterError {
    fn from(error: std::io::Error) -> Self {
        Self::Io(error)
    }
}

pub type UpdaterResult<T> = Result<T, UpdaterError>;
