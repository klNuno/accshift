// Writes src/display/fold_table.rs: every code point whose search fold
// (`foldSearchText` in src/lib/app/useDisplayPipeline.svelte.ts without the
// final lowercase: NFD, then U+0300..U+036F removed) differs from itself.
// U+0300..U+036F (folded to nothing) and the Hangul syllables (decomposed by
// rule) are left to the Rust code. Run with Node from crates/accshift-app:
//   node tests/data/display/gen_fold_table.mjs
import { writeFileSync } from "node:fs";

const BACKSLASH = String.fromCharCode(92);

const rows = [];
for (let cp = 0; cp < 0x110000; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  if (cp >= 0xac00 && cp <= 0xd7a3) continue;
  if (cp >= 0x300 && cp <= 0x36f) continue;
  const s = String.fromCodePoint(cp);
  const folded = s.normalize("NFD").replace(/[̀-ͯ]/g, "");
  if (folded !== s) rows.push([cp, folded]);
}

const esc = (text) =>
  [...text].map((c) => `${BACKSLASH}u{${c.codePointAt(0).toString(16)}}`).join("");
const lines = [];
for (let i = 0; i < rows.length; i += 4) {
  lines.push(
    "    " +
      rows
        .slice(i, i + 4)
        .map(([cp, text]) => `(0x${cp.toString(16)}, "${esc(text)}"),`)
        .join(" "),
  );
}
const out = `//! Generated by tests/data/display/gen_fold_table.mjs (Node ${process.versions.node},
//! Unicode ${process.versions.unicode}). Do not edit by hand.
//!
//! Each code point whose \`normalize("NFD")\` minus U+0300..U+036F differs
//! from itself, with that result, sorted by code point.

#[rustfmt::skip]
pub(super) static FOLD_TABLE: [(u32, &str); ${rows.length}] = [
${lines.join("\n")}
];
`;
writeFileSync(new URL("../../../src/display/fold_table.rs", import.meta.url), out);
console.log(`${rows.length} rows written to src/display/fold_table.rs`);
