// Writes src/platform-icons.js from the GUI's platform logos
// (crates/accshift-egui/src/ui/components/platform_icons.rs). The test
// "platform icons match the GUI" fails when the two drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const RUST_ICONS = join(
  here,
  "..",
  "..",
  "..",
  "crates",
  "accshift-egui",
  "src",
  "ui",
  "components",
  "platform_icons.rs",
);

/** The `(id, fill_path!("d"))` pairs of the Rust source. */
export function readRustIcons(source = readFileSync(RUST_ICONS, "utf8")) {
  const icons = {};
  for (const match of source.matchAll(/\("([a-z0-9-]+)", fill_path!\("([^"]+)"\)\)/g)) {
    icons[match[1]] = match[2];
  }
  return icons;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const icons = readRustIcons();
  const body = Object.entries(icons)
    .map(([id, d]) => `  ${JSON.stringify(id)}:\n    ${JSON.stringify(d)},`)
    .join("\n");
  const out = `// Generated by scripts/sync-icons.mjs from the GUI's platform logos
// (crates/accshift-egui/src/ui/components/platform_icons.rs): 24x24
// fill paths. Do not edit by hand.
export const PLATFORM_ICON_PATHS = Object.freeze({
${body}
});
`;
  writeFileSync(join(here, "..", "src", "platform-icons.js"), out);
  console.log(`wrote ${Object.keys(icons).length} platform icons`);
}
